/**
 * Converts public/lotus_inverted.jpg into ASCII art at src/components/lotus.ascii.ts.
 * Run with `npm run lotus` after changing the image or the settings below.
 */
import { writeFile } from 'node:fs/promises';
import { Jimp } from 'jimp';

const SOURCE = new URL('../public/lotus_inverted.jpg', import.meta.url);
const TARGET = new URL('../src/components/lotus.ascii.ts', import.meta.url);

/** Output width in characters. */
const COLS = 216;
/** Monospace cells are about twice as tall as they are wide. */
const CELL_ASPECT = 0.5;
/** Dim → bright; the image is white line art on black. */
const RAMP = ' .:-=+*#%@';
/** Pixels at or below this brightness count as background when cropping. */
const BACKGROUND = 40;
/** Below 1 lifts faint strokes so thin lines survive downscaling. */
const GAMMA = 0.6;

const brightness = (data: Buffer, i: number) => (data[i] + data[i + 1] + data[i + 2]) / 3;

const image = await Jimp.read(SOURCE.pathname);

// Crop to the flower's bounding box, so the margins don't eat the character budget.
const { width, height, data } = image.bitmap;
let [left, top, right, bottom] = [width, height, 0, 0];
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    if (brightness(data, (y * width + x) * 4) > BACKGROUND) {
      [left, top, right, bottom] = [Math.min(left, x), Math.min(top, y), Math.max(right, x), Math.max(bottom, y)];
    }
  }
}
image.crop({ x: left, y: top, w: right - left + 1, h: bottom - top + 1 });

const rows = Math.round((COLS * image.bitmap.height * CELL_ASPECT) / image.bitmap.width);
image.resize({ w: COLS, h: rows });

const cells = image.bitmap.data;
const levels = Array.from({ length: COLS * rows }, (_, i) => brightness(cells, i * 4) / 255);
const peak = Math.max(...levels);

/** Brightness per cell, one symbol each: ' ' is background, then 1…z step up to full brightness. */
const LEVELS = ' 123456789abcdefghijklmnopqrstuvwxyz';
const STEPS = LEVELS.length - 1;

const glyph = (level: number) => RAMP[Math.min(RAMP.length - 1, Math.floor(level * RAMP.length))];

const grid = Array.from({ length: rows }, (_, y) =>
  Array.from({ length: COLS }, (_, x) => (levels[y * COLS + x] / peak) ** GAMMA),
);

// Cells that would draw as a blank stay background, so the animation never sprinkles the dark around the flower.
const encoded = grid.map((row) =>
  row.map((level) => (glyph(level) === ' ' ? ' ' : LEVELS[Math.max(1, Math.round(level * STEPS))])).join(''),
);

await writeFile(
  TARGET,
  `// Generated by scripts/generate-lotus.ts from public/lotus_inverted.jpg — do not edit, run \`npm run lotus\`.

/** Character ramp, dim → bright. */
export const LOTUS_RAMP = ${JSON.stringify(RAMP)};

/** Brightness symbols, background → full: a cell's level is its index / (length - 1). */
export const LOTUS_LEVELS = ${JSON.stringify(LEVELS)};

/** Brightness of each cell, as LOTUS_LEVELS symbols. */
export const LOTUS = ${JSON.stringify(encoded, null, 2)};
`,
);

console.log(grid.map((row) => row.map(glyph).join('')).join('\n'));
